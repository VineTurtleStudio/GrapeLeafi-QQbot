export function dailyNum(uid, key, todayKey = new Date().toISOString().slice(0, 10)) {
  let h = 2166136261;
  const s = todayKey + ":" + key + ":" + uid;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return (h >>> 0) % 100;
}

